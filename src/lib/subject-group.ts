function normalize(value: string): string {
  return value
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[\s　・･_\-ー―.,，、。/／()（）\[\]【】「」『』]/g, "");
}

function nameMatches(names: string[], courseName: string): boolean {
  const normalized = normalize(courseName);
  return names.some((name) => normalize(name) === normalized);
}

/**
 * 科目の基幹科目群／総合科目群を、学生の入学年度に応じたルールで判定する。
 * 2026年度入学者以降は科目名の接頭辞（大学のシラバスサイト上の正式名称に
 * 含まれる）で判定し、2023〜2025年度入学者は旧カリキュラムの科目名リストで
 * 判定する。どちらにも該当しない科目（教職課程科目や、いずれの群にも
 * 属さない通常科目）はundefinedを返す（推測でタグ付けしない）。
 */
export function getSubjectGroup(course: Course, entryYear: number): SubjectGroup | undefined {
  if (entryYear <= 2025) {
    if (nameMatches(LEGACY_SOGO_KAMOKU_NAMES, course.name)) return "総合科目";
    if (nameMatches(LEGACY_KIKAN_KAMOKU_NAMES, course.name)) return "基幹科目";
    return undefined;
  }
  if (course.name.startsWith("基幹科目群")) return "基幹科目";
  if (course.name.startsWith("総合科目群")) return "総合科目";
  return undefined;
}
